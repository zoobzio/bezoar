/**
 * The config file the CLI looks for in the project root when `--config` is
 * not given.
 */
export const FILENAME = "bezoar.config.ts";

/**
 * The default directory of migrations, relative to the project root.
 */
export const MIGRATIONS = "src/migrations";

/**
 * The default directory of seeds, relative to the project root.
 */
export const SEEDS = "src/seeds";

/**
 * The default directory of queries, relative to the project root.
 */
export const QUERIES = "src/queries";

/**
 * The default directory of roles, relative to the project root.
 */
export const ROLES = "src/roles";

/**
 * The default output directory, relative to the project root.
 */
export const OUT_DIR = "bezoar";

/**
 * The extension of a source file.
 */
export const EXTENSION = ".sql";

/**
 * Matches a migration whose file name starts with digits and an underscore,
 * as in `0001_events.sql`. The digits are the version. The rest is the name.
 * A file name of another form is its own version and name.
 */
export const MIGRATION = /^(\d+)_(.+)$/;

/**
 * The schema of the database the kit reads the enums from.
 */
export const SCHEMA = "public";

/**
 * The manifest a write leaves in the output directory: the paths it
 * produced, so the next write can remove the ones it no longer produces
 * without touching anything the kit did not write.
 */
export const MANIFEST = ".bezoar.json";

/**
 * The banner at the top of each emitted module.
 */
export const BANNER = "// Generated by @bezoar/kit. Do not edit by hand.";

/**
 * Matches a line that is blank or a line comment. A query file of such lines
 * alone has no SQL.
 */
export const SILENT = /^\s*(--.*)?$/;

/**
 * The host the hermetic database listens on for the describe of each query.
 */
export const HOST = "127.0.0.1";

/**
 * The database and the user of a PGlite instance.
 */
export const DATABASE = "postgres";

/**
 * The key of the catalog cache SafeQL keeps for a build.
 */
export const CACHE = "bezoar";
